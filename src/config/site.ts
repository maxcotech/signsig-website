/**
 * Absolute site origin, without a trailing slash.
 *
 * `metadataBase` is derived from this. If it is wrong, every canonical URL, OG
 * image URL and sitemap entry is silently wrong in production — which nobody
 * notices until launch. Set NEXT_PUBLIC_SITE_URL in the deployment environment.
 */
export function getSiteUrl(): string {
  const raw = process.env.NEXT_PUBLIC_SITE_URL?.trim();
  if (raw) return raw.replace(/\/+$/, "");
  // Vercel provides this automatically for preview deployments.
  const vercel = process.env.NEXT_PUBLIC_VERCEL_URL?.trim();
  if (vercel) return `https://${vercel.replace(/\/+$/, "")}`;
  return "http://localhost:3000";
}

