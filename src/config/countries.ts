export type CountryOption = { code: string; name: string };

/**
 * Codes paired with English display names, sorted by name.
 *
 * `Intl.DisplayNames` is available in every browser this project targets and
 * in Node, so this evaluates identically on the server and the client — no
 * hydration mismatch. If a code has no name it falls back to the code itself
 * rather than rendering an empty option.
 */
export const COUNTRIES: readonly CountryOption[] = (() => {
  const names = new Intl.DisplayNames(["en"], { type: "region" });
  return ISO_CODES.map((code) => ({
    code,
    name: names.of(code) ?? code,
  })).sort((a, b) => a.name.localeCompare(b.name, "en"));
})();
